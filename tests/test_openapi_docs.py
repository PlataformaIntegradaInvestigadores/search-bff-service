import pytest
from fastapi.testclient import TestClient

from app.main import OPENAPI_TAGS, app

client = TestClient(app)
HTTP_METHODS = {"get", "post", "put", "patch", "delete"}


@pytest.fixture(scope="module")
def schema():
    response = client.get("/openapi.json")
    assert response.status_code == 200
    return response.json()


def _operations(schema):
    for path, item in schema["paths"].items():
        for method, operation in item.items():
            if method in HTTP_METHODS:
                yield path, method, operation


def test_info_describes_the_service(schema):
    info = schema["info"]
    assert info["version"] == "2.0.0"
    assert info["summary"]
    assert "Errores" in info["description"]
    assert schema["servers"] == [{"url": "/api/search/v2", "description": "Gateway"}]


def test_every_operation_is_documented(schema):
    for path, method, operation in _operations(schema):
        label = f"{method.upper()} {path}"
        assert operation.get("summary"), f"{label} sin summary"
        assert operation.get("description"), f"{label} sin descripción"
        assert operation.get("tags"), f"{label} sin tag"


def test_tags_are_declared_with_a_description(schema):
    declared = {tag["name"] for tag in schema["tags"]}
    assert declared == {tag["name"] for tag in OPENAPI_TAGS}
    assert all(tag["description"] for tag in schema["tags"])
    used = {tag for _, _, op in _operations(schema) for tag in op["tags"]}
    assert used == declared


def test_every_operation_declares_a_typed_success_response(schema):
    for path, method, operation in _operations(schema):
        content = operation["responses"]["200"]["content"]["application/json"]
        assert content.get("schema") not in (None, {}), f"{method.upper()} {path}"


def test_every_schema_property_has_a_description(schema):
    for name, definition in schema["components"]["schemas"].items():
        for prop, spec in definition.get("properties", {}).items():
            described = spec.get("description") or any(
                "description" in part for part in spec.get("allOf", [])
            )
            assert described, f"{name}.{prop} sin descripción"


def test_error_responses_match_what_each_endpoint_can_return(schema):
    paths = schema["paths"]
    assert sorted(paths["/search/filters"]["get"]["responses"]) == ["200"]
    assert sorted(paths["/cache/stats"]["get"]["responses"]) == ["200"]
    assert "404" in paths["/articles/{scopus_id}"]["get"]["responses"]
    assert "422" in paths["/search"]["post"]["responses"]
    assert "422" not in paths["/authors/{scopus_id}"]["get"]["responses"]


def test_autogenerated_422_is_not_published(schema):
    # validation_exception_handler responde 400 con ErrorResponse, nunca 422 de FastAPI.
    for path, method, operation in _operations(schema):
        response = operation["responses"].get("422")
        if response:
            ref = response["content"]["application/json"]["schema"]["$ref"]
            assert ref.endswith("ErrorResponse"), f"{method.upper()} {path}"
    assert "HTTPValidationError" not in schema["components"]["schemas"]


def test_every_response_has_a_description_in_spanish(schema):
    for path, method, operation in _operations(schema):
        for code, response in operation["responses"].items():
            label = f"{method.upper()} {path} {code}"
            assert response.get("description"), label
            assert response["description"] not in {
                "Successful Response",
                "Validation Error",
            }, label


def test_operation_ids_are_short_and_unique(schema):
    ids = [op["operationId"] for _, _, op in _operations(schema)]
    assert len(ids) == len(set(ids))
    assert all("_api_se_v2_" not in operation_id for operation_id in ids)


def test_no_autogenerated_titles_on_properties_and_parameters(schema):
    for definition in schema["components"]["schemas"].values():
        for prop in definition.get("properties", {}).values():
            assert "title" not in prop
    for _, _, operation in _operations(schema):
        for parameter in operation.get("parameters", []):
            assert "title" not in parameter["schema"]
            assert parameter.get("description"), parameter["name"]
